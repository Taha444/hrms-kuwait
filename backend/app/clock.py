# -*- coding: utf-8 -*-
"""اليوم في الكويت — مصدر واحد لكل ما يُحسب على «اليوم».

ROOT CAUSE: كل موضع يحسب أيًاما متبقية كان يستدعي ``date.today()``، وهي
تقرأ **توقيت الخادم**. والمجدول مضبوط على ``Asia/Kuwait`` صراحة
(scheduler.py). فالنظام يحمل ساعتين: واحدة تقرّر متى يُرسَل التنبيه،
وأخرى تقرّر كم يوًما تبقّى.

على خادم بتوقيت UTC — وهو الشائع في الاستضافة، وبيئتنا على Railway منها —
الفارق ثلاث ساعات. فبين منتصف الليل والثالثة فجًرا بتوقيت الكويت يكون
الخادم ما زال في اليوم السابق: التنبيه يقول «ستّة أيام» ولوحة المستخدم
تقول «أربعة»، والرقمان صادران عن النظام نفسه. هذا بالضبط ما أبلغ عنه
المستخدم في أول بلاغ عن شاشة التجديد.

الكويت UTC+3 ثابتًا بلا توقيت صيفي، فالتحويل بسيط ولا يحتاج جدول مناطق.
"""
from __future__ import annotations

from datetime import date, datetime, timedelta, timezone

#: الكويت UTC+3 دائًما — لا انتقال صيفي/شتوي منذ إلغائه عام 1990.
KUWAIT_TZ = timezone(timedelta(hours=3))


def today() -> date:
    """اليوم بتوقيت الكويت — استعملها بدل ``date.today()`` في أي حساب أيام."""
    return datetime.now(KUWAIT_TZ).date()


def now() -> datetime:
    """اللحظة الحالية بتوقيت الكويت (واعية بالمنطقة)."""
    return datetime.now(KUWAIT_TZ)


#: **القاعدُة المعلَنة: تُخزَّن اللحظاُت بـUTC، وتُعرَض بتوقيت الكويت.**
#:
#: قيس النظاُم فوُجدت ثالثُة أعراٍف لـ«الآن» تتعايش:
#:
#: 1. ``datetime.now()`` — عاريٌة بتوقيت المضيف (ستَّة عشر ملًفا).
#: 2. ``datetime.now(timezone.utc)`` — واعيٌة بـUTC (أربعٌة وعشرون ملًفا).
#: 3. ``clock.now()`` — واعيٌة بتوقيت الكويت.
#:
#: وأحَد عشر موضًعا يقرأ المحفوَظ **ويختمه UTC صراحًة**
#: (``replace(tzinfo=timezone.utc)``) — أي أن النظام كلَّه يفترض أن
#: المخزون UTC. وهذا الافتراُض صحيٌح ما دام المضيف UTC (وRailway منه)،
#: **ويكذب على مضيٍف كويتي بثالث ساعات** — عطٌل يعمل في بيئٍة ويصمت في
#: أخرى، وال يُمسَك باختباٍر يجري في بيئٍة واحدة.
#:
#: فالقاعدة: **ما يُخزَّن يُكتب بـ``datetime.now(timezone.utc)``**، وما
#: يُحسَب عليه «اليوم» يُقرأ من ``today()`` و``now()`` هنا. وال تُضاف
#: دالٌة رابعة لـ«الآن» — العرُف الثاني قائٌم في أربعٍة وعشرين ملًفا،
#: فتوحيُد الباقي عليه أقّل كلفًة من عرٍف جديد يزيدها.
#:
#: و``scripts/naive_clocks.py`` يُطبِع ما بقي عارًيا لمن يراجع.
_STORAGE_CLOCK_RULE = "UTC in storage, Kuwait on screen"


def days_until(target: date | None) -> int | None:
    """كم يوًما يفصلنا عن هذا التاريخ — سالب إن مضى.

    الحساب في دالة واحدة لا في كل موضع: ``(x - today()).days`` مكرّرة
    ثلاثين مرة تعني ثلاثين فرصة لاستعمال ساعة خاطئة.
    """
    if target is None:
        return None
    return (target - today()).days
