# -*- coding: utf-8 -*-
"""P3-15 — أنواع طلبات موضوعها تملكه وحدة مستقلة، فلا تُفتح كطلب.

**ما ظهر بالقياس، لا ما وصفه البند:**

REQSIG لم يكن مساًرا موازًيا — كان مساًرا **لا يصل**. أنشأه الموظف
بمرفق توقيعه وسببه، واعتمده HR، فرُدّ الطلب ``completed``… والتوقيع
بعده ``signature_path=None`` و``signature_version=0`` وسجلّ النسخ صفر.
لا شيء وقع، والشاشة تقول «مكتمل».

وأخطر ما فيه أن الشاشة تقوده إليه: زرّ «استبدال التوقيع» في الملف
الشخصي كان ينقل الموظف إلى نموذج REQSIG. فالباب المعروض هو المعطَّل،
والباب العامل (``POST /api/me/signature`` بسبب) لا يصل إليه أحد.

**ولماذا لا يُوصَل اعتماد REQSIG بتركيب التوقيع؟** لأن ذلك يصنع
المسار الموازي الذي يحذّر منه البند حًقا: التوقيع يُركَّب عندئذٍ من
موضعين، أحدهما يكتب ``UserSignatureVersion`` ويرفع النسخة ويُدقّق،
والآخر يقلّده. والتوقيع دليل يُحتجّ به على كل مستند وُقِّع، فسجلّ نسخه
لا يحتمل كاتًبا ثانًيا.

القاعدة إذن: **الموضوع لصاحبه**. من أراد تغيير توقيعه ذهب إلى وحدة
التوقيع، ومن أنشأ REQSIG رُدّ عليه بأين يذهب — لا بـ«مكتمل» كاذبة.

والإعلان هنا في موضع واحد يقرأه المانع والكتالوج مًعا، فيستحيل أن
يَعرض الكتالوج ما يرفضه الخادم — وهو ما حدث حرًفا في ``superseded_by``
قبل توحيدها.
"""
from __future__ import annotations

# الكود ← (الوحدة المالكة، أين يذهب صاحب الحاجة، لماذا لا يكون طلًبا)
MODULE_OWNED: dict[str, dict[str, str]] = {
    "REQSIG": {
        "module": "signatures",
        "where": "الملف الشخصي ← التوقيع ← «استبدال التوقيع»",
        "why": ("تغيير التوقيع يمرّ بوحدة التوقيع وحدها: النسخة القديمة "
                "تبقى سارية حتى يعتمد الاعتماد الجديد، وكل نسخة تُسجَّل في "
                "سجلّ لا يُعدَّل. فتحه كطلب ثانٍ يترك التوقيع بلا تغيير."),
    },
}


def owning_module(code: str) -> dict[str, str] | None:
    """هل موضوع هذا الكود تملكه وحدة مستقلة؟ يعيد بيانها أو ``None``."""
    return MODULE_OWNED.get((code or "").strip().upper())


def rejection_message(code: str) -> str:
    """رسالة الردّ: **أين يذهب**، لا «غير مسموح» وحدها.

    من يُمنع بلا وجهة يعيد المحاولة أو يستسلم؛ وكلاهما يترك حاجته قائمة.
    """
    info = owning_module(code) or {}
    where = info.get("where") or "الوحدة المختصّة"
    why = info.get("why") or ""
    return f"هذا لا يُفتح كطلب. {why} اذهب إلى: {where}."
