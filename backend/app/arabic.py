# -*- coding: utf-8 -*-
"""مطابقة الأسماء العربية — على صورتها المجرَّدة لا على حروفها كما كُتبت.

**العطل الذي أوجب هذا الملف**: اسم شركة واحد يُكتب في ثلاث صور داخل
مستنداتها الرسمية نفسها:

    شركة النيل الأزرق   ·   شركه النيل الازرق   ·   شركة النيل الازرق

والفارق همزٌة على ألف (``أ`` مقابل ``ا``) وتاٌء مربوطة (``ة`` مقابل
``ه``). والمطابقة الحرفية ترى ثلاثة أسماء حيث يرى القارئ اسًما واحًدا:
فبحثتُ عن «النيل الأزرق» في موقع يكتبها «النيل الازرق» فلم أجدها،
وقالت الأداة «أنشئ الشركة» وهي قائمة أمام عيني.

**وهذا ليس عيب بيانات بل عيب مطابقة**: الكتابة العربية تحتمل هذه الصور
كلّها، والجهات الرسمية نفسها لا تلتزم صورًة واحدة. فمن يطابق حرًفا بحرف
يخطئ في الكويت دائًما لا أحيانًا.

**ولا يُغيَّر المخزون**: الاسم يُحفظ كما كتبه صاحبه. والتجريد للمقارنة
وحدها — تغيير ما هو مخزون يُفسد ما يُطبع على المستندات الرسمية.
"""
from __future__ import annotations

import re
import unicodedata

#: صور الألف كلّها تُردّ إلى ألف مجرَّدة.
_ALEF = {"أ": "ا",   # أ
         "إ": "ا",   # إ
         "آ": "ا",   # آ
         "ٱ": "ا"}   # ٱ

#: وما يتبادل في الكتابة العامّة بلا فرق في القراءة.
_SWAP = {"ة": "ه",   # ة ← ه
         "ى": "ي",   # ى ← ي
         "ؤ": "و",   # ؤ ← و
         "ئ": "ي"}   # ئ ← ي

#: التشكيل والتطويل: زينٌة لا تُميّز اسًما عن اسم.
_STRIP = re.compile(r"[ـً-ْٰۖ-ۭ]")


def normalize_ar(text: str | None) -> str:
    """الصورة المجرَّدة للاسم — للمقارنة وحدها، لا للحفظ ولا للعرض."""
    if not text:
        return ""
    s = unicodedata.normalize("NFKC", str(text))
    s = _STRIP.sub("", s)
    s = "".join(_ALEF.get(c, _SWAP.get(c, c)) for c in s)
    # الفراغات المتعدّدة والأطراف: «شركة  النيل» و«شركة النيل» اسٌم واحد.
    return re.sub(r"\s+", " ", s).strip().casefold()


def contains_ar(haystack: str | None, needle: str | None) -> bool:
    """هل يقع الاسم الثاني داخل الأول — بصرف النظر عن صورة كتابته؟"""
    n = normalize_ar(needle)
    return bool(n) and n in normalize_ar(haystack)


def same_ar(a: str | None, b: str | None) -> bool:
    """اسمان يقرؤهما الناس واحًدا."""
    return normalize_ar(a) == normalize_ar(b) != ""
