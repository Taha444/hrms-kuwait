# -*- coding: utf-8 -*-
"""TSK-03 — ما هو «مهمة» وما هو «إشعار».

المعيار واحد: **لو لم يفعل المستخدم شيًئا، هل يتعطّل عمل؟** نعم = مهمة،
لا = إشعار. وبهذا المعيار وحده تُفرز الصفوف، لا بمكان ظهورها في الواجهة.

**ولماذا هنا لا في وحدة الواجهة**: التعريف كان يعيش في ``routers/tasks``،
فمن يعرض المهام يعرف الفرق ومن يغلقها لا يعرفه. فكان ``_close_open_tasks``
يكنس كل ما يتعلّق بطلب وصل حالة نهائية — بما فيه إخطار النتيجة نفسه،
فيُحرَم الموظف من معرفة ما جرى بطلبه.

ولم يظهر ذلك لأن الإخطار كان ينجو بمحض توقيت: يُنشأ في الجلسة ولا
يُكتب في القاعدة بعد، فلا يراه استعلام الإغلاق. سلوك صحيح مسنود إلى
مصادفة ينكسر أول مرة يتغيّر فيها توقيت الكتابة — وهو ما حدث.
"""
from __future__ import annotations

#: أنواع تُقرأ ولا تُنفَّذ.
NOTIFICATION_TYPES = {
    "request_update",   # «تم اعتماد/رفض طلبك» — خبر لا إجراء
    "digest",           # ملخّص دوري
    "sla_escalation",   # تنبيه تأخّر — الإجراء على المهمة الأصلية لا عليه
    # P1-03 — «جاهز للطباعة»: بعد أن صار المستند يدخل أرشيف الموظف عند
    # صدوره، لا يتعطّل شيء إن لم يطبعه أحد — والطباعة أثر ورقي اختياري.
    #
    # وكان تصنيفه مهمًة يُخفيه لا يُظهره: يُنشأ عند اكتمال الطلب ثم يكنسه
    # ``_close_open_tasks`` في اللحظة نفسها، فقرأتُه ``dismissed`` قبل أن
    # يراه أحد. فالطريق الوحيد إلى الأرشيف كان يُغلق قبل أن يُفتح.
    "ready_to_print",
}


def is_notification(task_type: str | None) -> bool:
    return task_type in NOTIFICATION_TYPES


def inbox_query(user_id: int, status: str | None = "open",
                kind: str | None = None):
    """استعلام صندوق مستخدم. **العدّاد والقائمة يستعملانه معًا.**

    TSK-03 — العدّاد كان يعدّ كل صفوف المستخدم المفتوحة، والصندوق يعرضها
    كلها: أربعة وأربعون عنصًرا عند شؤون الموظفين، ستة منها تحتاج إجراًء
    وثمانية وثلاثون أخبار. ورقم بهذا الحجم يُقرأ كعمل متأخّر فيُهمَل كلّه،
    والستة التي تُعطّل العمل تضيع بينها.

    و``kind`` هو الفرق: ``task`` ما يحتاج إجراًء، ``notification`` ما
    يُقرأ. وغيابه يعني الاثنين معًا — للتوافق مع من يريد الصندوق كاملًا.
    """
    from sqlalchemy import select

    from . import models

    q = select(models.Task).where(models.Task.assignee_user_id == user_id)
    if status:
        q = q.where(models.Task.status == status)
    if kind == "task":
        q = q.where(models.Task.type.notin_(tuple(NOTIFICATION_TYPES)))
    elif kind == "notification":
        q = q.where(models.Task.type.in_(tuple(NOTIFICATION_TYPES)))
    return q
