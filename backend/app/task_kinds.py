# -*- coding: utf-8 -*-
"""TSK-03 — ما هو «مهمة» وما هو «إشعار».

المعيار واحد: **لو لم يفعل المستخدم شيًئا، هل يتعطّل عمل؟** نعم = مهمة،
لا = إشعار. وبهذا المعيار وحده تُفرز الصفوف، لا بمكان ظهورها في الواجهة.

**ولماذا هنا لا في وحدة الواجهة**: التعريف كان يعيش في ``routers/tasks``،
فمن يعرض المهام يعرف الفرق ومن يغلقها لا يعرفه. فكان ``_close_open_tasks``
يكنس كل ما يتعلّق بطلب وصل حالة نهائية — بما فيه إخطار النتيجة نفسه،
فيُحرَم الموظف من معرفة ما جرى بطلبه.

ولم يظهر ذلك لأن الإخطار كان ينجو بمحض توقيت: يُنشأ في الجلسة ولا
يُكتب في القاعدة بعد، فلا يراه استعلام الإغلاق. سلوك صحيح مسنود إلى
مصادفة ينكسر أول مرة يتغيّر فيها توقيت الكتابة — وهو ما حدث.
"""
from __future__ import annotations

#: أنواع تُقرأ ولا تُنفَّذ.
NOTIFICATION_TYPES = {
    "request_update",   # «تم اعتماد/رفض طلبك» — خبر لا إجراء
    "digest",           # ملخّص دوري
    "sla_escalation",   # تنبيه تأخّر — الإجراء على المهمة الأصلية لا عليه
}


def is_notification(task_type: str | None) -> bool:
    return task_type in NOTIFICATION_TYPES
