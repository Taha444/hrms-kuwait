/**
 * فتح مستند مولَّد في نافذة وطباعته.
 *
 * ROOT CAUSE: كل موضع كان يفتح نافذة فارغة ويكتب فيها الـHTML، والزر داخل
 * ذلك الـHTML يستعمل `onclick="window.print()"` مضمًَّنا. ومستند `about:blank`
 * المكتوب عبر `document.write` **يرث سياسة أمان المحتوى للصفحة الأم**، وهي
 * عندنا `script-src 'self'` بلا `unsafe-inline` — وهذا صواب ولا نريد تخفيفه.
 * فيُحجب المعالِج المضمَّن: الزر يبدو سليًما، والضغط عليه لا يفعل شيًئا، وبلا
 * أي رسالة. فشل صامت يقف أمامه المستخدم ولا يعرف أن المشكلة ليست عنده.
 *
 * الحلّ: الطباعة تُستدعى **من هنا** — من كود مُحمَّل كحزمة تسمح بها السياسة —
 * لا من سطر داخل المستند. والمستند يبقى كما هو، فزرّه يعمل أو لا يعمل، ونحن
 * لا نعتمد عليه.
 */

/** يفتح الـHTML في نافذة ويستدعي الطباعة. يعيد false إن حجب المتصفح النافذة. */
export function openAndPrint(html: string, autoPrint = true): boolean {
  const w = window.open("", "_blank");
  if (!w) return false; // مانع النوافذ المنبثقة — يخبر المستدعي ليعرض رسالة

  w.document.write(html);
  w.document.close();
  w.focus();

  if (!autoPrint) return true;

  // الانتظار حتى تكتمل الموارد: الطباعة قبل تحميل الخطوط تُخرج صفحة بخط بديل،
  // والعقد الحكومي عربي — خطّ بديل يعني مستنًدا مشوًَّها يُقدَّم لجهة رسمية.
  const print = () => {
    try {
      w.focus();
      w.print();
    } catch {
      /* أُغلقت النافذة قبل الطباعة — لا شيء نفعله */
    }
  };

  if (w.document.readyState === "complete") {
    // مهلة قصيرة تُتيح تطبيق الأنماط قبل أخذ اللقطة
    w.setTimeout(print, 250);
  } else {
    w.addEventListener("load", () => w.setTimeout(print, 250), { once: true });
  }
  return true;
}
